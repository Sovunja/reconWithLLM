package core

import "context"

// Module — контракт, который реализует каждый модуль системы
// (веб-краулинг, парсинг, ИИ-анализ, генерация отчётов и т.д.).
//
// Ядро не знает о конкретных типах модулей — оно работает только с этим
// интерфейсом. Это позволяет:
//   1) Подключать новые модули без изменения ядра.
//   2) Заменять модули в эксперименте (например, ИИ-краулер вместо обычного).
//   3) Тестировать модули изолированно через моки.
//
// Жизненный цикл модуля строго управляется ядром:
//   Init -> Run (несколько раз для разных сканов) -> Shutdown.
type Module interface {
	// Name возвращает уникальное имя модуля. По нему ядро находит модуль
	// в реестре и описывает шаги pipeline в конфигурации.
	Name() string

	// Init вызывается один раз при старте системы. Модуль получает доступ
	// к ядру (Kernel) для публикации событий и взаимодействия с другими
	// модулями через шину. Здесь модуль готовит ресурсы: открывает
	// HTTP-клиенты, загружает клиент LLM, инициализирует пулы.
	Init(ctx context.Context, kernel *Kernel) error

	// Run выполняет основную работу модуля над конкретным контекстом скана.
	// Модуль читает входные данные через ScanContext.Get(), производит работу
	// и складывает результаты обратно через ScanContext.Set().
	// context.Context используется для отмены и таймаутов.
	Run(ctx context.Context, scan *ScanContext) error

	// Shutdown вызывается при остановке системы. Модуль освобождает
	// ресурсы: закрывает соединения, сохраняет состояние, останавливает
	// фоновые горутины.
	Shutdown(ctx context.Context) error
}

// EventSubscriber — опциональный интерфейс. Если модуль его реализует,
// ядро будет доставлять ему события из шины. Это нужно, например,
// модулю анализа в Сценарии 2: краулер публикует событие "url.found",
// а ИИ-аналайзер реагирует и принимает решение о приоритете URL.
type EventSubscriber interface {
	// Subscriptions возвращает список типов событий, на которые
	// подписан модуль. Например: ["url.found", "email.extracted"].
	Subscriptions() []string

	// HandleEvent обрабатывает входящее событие. Вызывается ядром
	// в отдельной горутине, чтобы не блокировать публикатора.
	HandleEvent(ctx context.Context, event Event, scan *ScanContext) error
}

// AIAsker — опциональный интерфейс для модулей, поддерживающих
// интерактивный Q&A режим (Сценарий 1: passive_ai).
//
// Реализуется AIAnalyzerModule. Веб-интерфейс находит модуль с этим
// интерфейсом через type assertion и вызывает Ask() при поступлении
// вопроса от пользователя.
//
// Интерфейс живёт в core, чтобы пакет modules/webui не зависел от
// modules — это сохраняет одностороннюю зависимость webui → core.
type AIAsker interface {
	// Ask отправляет один пользовательский вопрос в LLM и возвращает
	// текст ответа. Метод сам собирает релевантный контекст из scan
	// и истории диалога; вызывающая сторона (webui) отвечает только
	// за хранение истории через ScanRecord.AppendMessage.
	Ask(ctx context.Context, scan *ScanContext, history []ChatMessage, question string) (string, error)
}
